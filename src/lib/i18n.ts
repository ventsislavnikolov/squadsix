const DICTS: Record<Lang, Dict> = { bg, en };

export function useI18n() {
  const { data: session } = useSuspenseQuery(sessionQuery);
  const lang = session.lang;
  const t = DICTS[lang];
  return {
    lang,
    isAdmin: session.isAdmin,
    t,
    /** A person's short name in the page's language. */
    name: (n: ShortName | undefined) => (n ? n[lang] : "?"),
    /** A server refusal code, worded. */
    error: (err: unknown) => {
      const code = err instanceof Error ? err.message : "";
      return (t.errors as Record<string, string>)[code] ?? t.errors.generic;
    },
  };
}
